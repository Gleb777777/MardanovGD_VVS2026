import pandas as pd
import numpy as np

products = [
    ("Хлеб", "Выпечка", 40, 120, "Центр"),
    ("Молоко", "Молочное", 80, 95, "Центр"),
    ("Сыр", "Молочное", 450, 30, "Север"),
    ("Яблоки", "Фрукты", 120, 60, "Юг"),
    ("Бананы", "Фрукты", 90, 75, "Юг"),
    ("Чай", "Напитки", 150, 40, "Север"),
    ("Кофе", "Напитки", 400, 25, "Центр"),
    ("Шоколад", "Сладкое", 100, 80, "Север"),
    ("Печенье", "Сладкое", 70, np.nan, "Юг"),
    ("Сок", "Напитки", 110, 55, "Центр"),
    ("Вода", "Напитки", 50, 150, "Север"),
    ("Йогурт", "Молочное", 60, 70, "Юг"),
    ("Масло", "Молочное", 200, 35, "Центр"),
    ("Макароны", "Крупы", 80, 65, "Север"),
    ("Рис", "Крупы", 110, 50, "Юг"),
    ("Гречка", "Крупы", 95, 45, "Центр"),
    ("Колбаса", "Мясо", 380, 28, "Север"),
    ("Курица", "Мясо", 290, 33, "Юг"),
    ("Мыло", "Хозтовары", 45, 90, "Центр"),
    ("Шампунь", "Хозтовары", np.nan, 20, "Север"),
]

columns = ["Товар", "Категория", "Цена", "Количество", "Магазин"]
df = pd.DataFrame(products, columns=columns)

print("Первые 5 строк")
print(df.head())
print("\nРазмер таблицы:", df.shape)
print("Столбцы:", list(df.columns))
print("\nТипы данных")
print(df.dtypes)

print("\nСтатистика по цене и количеству")
print(df[["Цена", "Количество"]].describe())
print("\nПропуски до заполнения")
print(df.isna().sum())

for column in ["Цена", "Количество"]:
    df[column] = df[column].fillna(df[column].median())

print("\nПропуски после заполнения")
print(df.isna().sum())

df["Выручка"] = df["Цена"] * df["Количество"]

prices = df["Цена"].to_numpy()
print("\nСредняя цена:", round(np.mean(prices), 2))
print("Минимальная цена:", np.min(prices))
print("Максимальная цена:", np.max(prices))
print("Стандартное отклонение:", round(np.std(prices), 2))

print("\nОбщая выручка:", df["Выручка"].sum())
print("Средняя выручка на товар:", round(df["Выручка"].mean(), 2))
best = df.loc[df["Выручка"].idxmax()]
print("Товар с самой большой выручкой:", best["Товар"], "-", best["Выручка"])

expensive = df[df["Цена"] > 200]
print("\nТоваров дороже 200:", len(expensive))
print(expensive[["Товар", "Цена"]])

milk = df[df["Категория"] == "Молочное"]
milk = milk[milk["Количество"] > 50]
print("\nМолочных товаров с количеством больше 50:", len(milk))

center = df[df["Магазин"] == "Центр"]
print("Товаров в магазине «Центр»:", len(center))

print("\nВыручка по категориям")
print(df.groupby("Категория")["Выручка"].sum().sort_values(ascending=False))
print("\nВыручка по магазинам")
print(df.groupby("Магазин")["Выручка"].sum())
print("\nСредняя цена и количество по категориям")
print(df.groupby("Категория")[["Цена", "Количество"]].mean().round(2))

df.to_csv("shop_processed.csv", index=False)
print("\nФайл shop_processed.csv сохранён")
